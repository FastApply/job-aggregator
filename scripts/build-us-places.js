#!/usr/bin/env node
/**
 * Writes src/utils/us-places-data.js: the towns of each US state whose two-letter code is also an
 * ISO country code (CA, NC, IL, GA, CO, ...), read by location-countries.js.
 *
 *   curl -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_place_national.zip
 *   unzip 2024_Gaz_place_national.zip
 *   node scripts/build-us-places.js 2024_Gaz_place_national.txt > src/utils/us-places-data.js
 *
 * Source: US Census Bureau Gazetteer, places (incorporated places and census-designated places),
 * a public-domain work of the US Government. DE is left out: Delaware keeps its own town list
 * (DELAWARE_TOWNS), because about half the bare "City, DE" rows are German. PR, VI and GU are
 * left out: their codes are their own ISO codes and already read as both.
 */
const fs = require('fs');
const { NAME } = require('../src/utils/location-countries');
const { placeKey } = require('../src/utils/us-places');

const SKIP = new Set(['de', 'pr', 'vi', 'gu']);
// The legal description the Census appends to every name ("Morgan Hill city", "Highlands Ranch
// CDP", "Nashville-Davidson metropolitan government (balance)").
const LSAD = / (?:city and borough|city|town|village|borough|CDP|municipality|plantation|corporation)$/;
// A consolidated city-county is written "Macon-Bibb County", "Nashville-Davidson metropolitan
// government (balance)", "Louisville/Jefferson County metro government (balance)": postings write
// the city alone, so its first part is kept as well.
const CONSOLIDATED = / (?:(?:consolidated|unified|metropolitan|metro) government|urban county)$/;
function names(raw) {
  let name = raw.replace(/ \(balance\)$/, '');
  const merged = CONSOLIDATED.test(name) || name !== raw;
  name = name.replace(CONSOLIDATED, '').replace(LSAD, '');
  const out = [name];
  const head = name.split(/[-/,]/)[0].trim();
  if (head !== name && (merged || /[-/,].*\bcounty\b/i.test(name))) out.push(head);
  return out;
}

const [file] = process.argv.slice(2);
if (!file) { console.error('usage: build-us-places.js <Gaz_place_national.txt>'); process.exit(1); }
const by = new Map();
for (const line of fs.readFileSync(file, 'utf8').split('\n').slice(1)) {
  const cols = line.split('\t');
  if (cols.length < 4) continue;
  const st = cols[0].trim().toLowerCase();
  if (SKIP.has(st) || !NAME.has(st)) continue;
  if (!by.has(st)) by.set(st, new Set());
  for (const name of names(cols[3].trim())) {
    const key = placeKey(name);
    if (key) by.get(st).add(key);
  }
}
const out = [
  '// Generated by scripts/build-us-places.js from the US Census Bureau 2024 Gazetteer (places),',
  '// a public-domain work. Do not edit by hand.',
  'module.exports = {',
];
for (const st of [...by.keys()].sort()) out.push(`  ${st}: '${[...by.get(st)].sort().join('|').replace(/'/g, "\\'")}',`);
out.push('};', '');
process.stdout.write(out.join('\n'));
